'''同一随机案例中，首次分歧发生在动作79。F4在前缀77处复查，否决F3原本选择的mirror1_unknown1：第二批预测反而多20.955秒。但在真实场景接同一F1的事后比较，这个被否决的候选本来更快48.757秒。因此微调确实会误拒好动作；实际整局从51.031变为51.421分钟，多23.385秒。该48.757秒是固定F1反事实，不是整个部署轨迹的实际总时差。''',
